#!/usr/bin/env bash
# Derive .env.dev (git-ignored) from .env for running the API and web app
# *natively* against the dockerised Postgres on 127.0.0.1:5432.
#
# .env holds the raw secrets (used by compose); .env.dev holds the exact
# variable names the .NET host and SvelteKit read, so `make dev`, `dotnet
# watch`, and the VS Code debugger (launch.json → envFile) all agree.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

if [[ ! -f .env ]]; then
  echo "scripts/dev-env.sh: .env not found — run \`make setup\` (or \`make secrets\`) first." >&2
  exit 1
fi

set -a
# shellcheck disable=SC1091
source ./.env
set +a

: "${POSTGRES_PASSWORD:?POSTGRES_PASSWORD is empty in .env — run make secrets}"
: "${JWT_SECRET:?JWT_SECRET is empty in .env — run make secrets}"

API_PORT="${API_PORT:-8080}"
WEB_PORT="${WEB_PORT:-5173}"

umask 077
cat > .env.dev <<ENV
# Generated by scripts/dev-env.sh from .env — do not edit, do not commit.
# ---- .NET API (apps/api/CouplesCash.Api) ----
ASPNETCORE_ENVIRONMENT=Development
ASPNETCORE_URLS=http://localhost:${API_PORT}
ConnectionStrings__Default="Host=localhost;Port=5432;Database=couplescash;Username=couplescash;Password=${POSTGRES_PASSWORD}"
Jwt__Secret=${JWT_SECRET}
Api__EnableDocs=true
DOTNET_ENVIRONMENT=Development
# Web Push: empty keys = push disabled (503). Fill them with \`make vapid\`.
Push__VapidPublicKey=${VAPID_PUBLIC_KEY:-}
Push__VapidPrivateKey=${VAPID_PRIVATE_KEY:-}
Push__Subject=${VAPID_SUBJECT:-mailto:dev@localhost}
# Passkeys: http://localhost is a secure context, so they work in dev without TLS.
WebAuthn__Origin=http://localhost:${WEB_PORT}
WebAuthn__RelyingPartyName=CouplesCash
# Background job (autopay, reminders, hygiene, bank sync). Set SCHEDULER_ENABLED=false in .env to pause it.
Scheduler__Enabled=${SCHEDULER_ENABLED:-true}
# Bank sync (SimpleFIN): empty key = disabled (503 bank_sync_not_configured). Fill it with \`make secrets\`.
Security__DataKey=${DATA_KEY:-}
Sync__IntervalHours=${SYNC_INTERVAL_HOURS:-6}
# ---- SvelteKit (apps/web) ----
API_URL=http://localhost:${API_PORT}
ORIGIN=http://localhost:${WEB_PORT}
ENV
echo "Wrote .env.dev (API → http://localhost:${API_PORT}, web → http://localhost:${WEB_PORT})"
